#!/usr/bin/env node
// Download complete WKT2 definitions; do not construct or rewrite EPSG metadata.
import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, unlink, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

export const DEFINITIONS = [
    [4326, 'GEOGCRS'],
    [25832, 'PROJCRS'],
    [25833, 'PROJCRS'],
    [1149, 'COORDINATEOPERATION'],
];

const DEFAULT_OUTPUT = fileURLToPath(new URL(
    '../src/commonMain/kotlin/cloud/mallne/geokit/coordinates/builtin/BuiltInCoordinateReferenceSystems.kt',
    import.meta.url,
));

export async function fetchWkt(code, kind, request = fetch) {
    const options = () => ({
        headers: { 'User-Agent': 'GeoKit EPSG definition generator', Accept: 'text/plain' },
        signal: AbortSignal.timeout(30_000),
    });
    let sourceUrl = `https://epsg.io/${code}.wkt2`;
    let response = await request(sourceUrl, options());
    let fromPage = false;
    if (response.status === 404) {
        // EPSG.io currently publishes operation 1149's WKT2 in its page, but its
        // linked .wkt2 download returns 404. Extract that text, never rebuild it.
        await response.body?.cancel();
        sourceUrl = `https://epsg.io/${code}`;
        response = await request(sourceUrl, options());
        fromPage = true;
    }
    if (!response.ok) throw new Error(`EPSG:${code}: HTTP ${response.status}`);
    let wkt = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(await response.arrayBuffer());
    if (fromPage) {
        const blocks = [...wkt.matchAll(/<pre\b[^>]*>([\s\S]*?)<\/pre>/gi)]
            .map((match) => match[1].replace(/<\/?span\b[^>]*>/gi, ''))
            .filter((text) => text.trimStart().startsWith(`${kind}[`));
        if (blocks.length !== 1) throw new Error(`Expected one published WKT2 block for EPSG:${code}`);
        const entities = { amp: '&', quot: '"', apos: "'", lt: '<', gt: '>', nbsp: '\u00a0' };
        wkt = blocks[0].replace(/&(#x[0-9a-f]+|#\d+|[a-z][a-z0-9]+);/gi, (_, entity) => {
            if (entity.startsWith('#')) {
                const hex = entity[1].toLowerCase() === 'x';
                return String.fromCodePoint(Number.parseInt(entity.slice(hex ? 2 : 1), hex ? 16 : 10));
            }
            if (!(entity in entities)) throw new Error(`Unknown HTML entity in WKT2: &${entity};`);
            return entities[entity];
        });
    }
    const identifier = new RegExp(`\\bID\\[\\s*"EPSG"\\s*,\\s*${code}\\s*\\]`);
    if (!wkt.trimStart().startsWith(`${kind}[`) || !identifier.test(wkt)) {
        throw new Error(`Unexpected WKT2 response for EPSG:${code}`);
    }
    return { wkt, sourceUrl };
}

export function kotlinLiteral(value) {
    const escapes = { '\\': '\\\\', '"': '\\"', $: '\\$', '\n': '\\n', '\r': '\\r', '\t': '\\t' };
    return `"${value.replace(/[\\"$\u0000-\u001f]/g, (char) =>
        escapes[char] ?? `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`,
    )}"`;
}

export function render(definitions) {
    const lines = [
        'package cloud.mallne.geokit.coordinates.builtin',
        '',
        '// Generated by coordinates/scripts/generate-builtin-crs.mjs. DO NOT EDIT.',
        '// WKT2 is downloaded verbatim; only Kotlin string escaping is applied.',
        'object BuiltInCoordinateReferenceSystems {',
    ];
    for (const [code, { wkt, sourceUrl }] of definitions) {
        const digest = createHash('sha256').update(wkt, 'utf8').digest('hex');
        lines.push(
            `    // ${sourceUrl} (SHA-256: ${digest})`,
            `    const val EPSG${code} = ${kotlinLiteral(wkt)}`,
            '',
        );
    }
    lines.push('}', '');
    return lines.join('\n');
}

export async function generate({ output = DEFAULT_OUTPUT, check = false, fetchDefinition = fetchWkt } = {}) {
    // Complete every download before touching the existing generated class.
    const definitions = new Map();
    for (const [code, kind] of DEFINITIONS) definitions.set(code, await fetchDefinition(code, kind));
    const content = render(definitions);
    if (check) {
        try {
            return (await readFile(output)).equals(Buffer.from(content, 'utf8'));
        } catch (error) {
            if (error.code === 'ENOENT') return false;
            throw error;
        }
    }

    await mkdir(dirname(output), { recursive: true });
    const temporary = join(dirname(output), `.${basename(output)}.${randomUUID()}.tmp`);
    try {
        await writeFile(temporary, content, { encoding: 'utf8', flag: 'wx' });
        await rename(temporary, output);
    } finally {
        await unlink(temporary).catch((error) => { if (error.code !== 'ENOENT') throw error; });
    }
    return true;
}

if (import.meta.main) {
    try {
        const { values } = parseArgs({ options: {
            output: { type: 'string' },
            check: { type: 'boolean', default: false },
            help: { type: 'boolean', default: false },
        } });
        if (values.help) {
            console.log('Usage: node coordinates/scripts/generate-builtin-crs.mjs [--check] [--output path]');
        } else {
            const output = values.output ? resolve(values.output) : DEFAULT_OUTPUT;
            const matches = await generate({ output, check: values.check });
            console.log(`${values.check ? (matches ? 'Up to date' : 'Out of date') : 'Generated'}: ${output}`);
            if (!matches) process.exitCode = 1;
        }
    } catch (error) {
        console.error(`Generation failed: ${error.message}`);
        process.exitCode = 1;
    }
}
